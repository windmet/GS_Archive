import assert from 'node:assert/strict'
import http from 'node:http'
import { readFile } from 'node:fs/promises'
import { createStoryAssetPlan } from '../shared/story/StoryAssetPlan.js'
import { Preloader } from '../src/utils/Preloader.js'
import { LipSyncController } from '../src/core/LipSyncController.js'
import { storyAssetAdapter } from '../src/utils/StoryAssetAdapters.js'
import { validateStoryConfig } from '../src/utils/StoryConfigShape.js'

const configKinds = ['idol-placement', 'idol-mouth', 'model-mouth', 'idol-body-types', 'idol-motion', 'costume-prefab-metadata', 'costume-dictionary']
const planFor = prefix => {
  const plan = createStoryAssetPlan({ steps: [{ step_id: 7, state: { spines: [{ id: '040ren', model: `${prefix}_001_00` }] } }] },
    { file: 'fixture.json', sha256: `sha256:${'a'.repeat(64)}` })
  // Bound this transport test to configuration tasks generated by the real plan.
  plan.assets = plan.assets.filter(asset => configKinds.includes(asset.kind))
  return plan
}
const requests = []
const server = http.createServer((request, response) => {
  requests.push(request.url)
  const prefix = request.url.match(/idol_mouth_stg_(.+)\.json$/)?.[1]
  response.setHeader('Content-Type', prefix === 'html' ? 'text/html; charset=utf-8' : 'application/json')
  if (prefix === 'slow') return
  if (prefix === 'missing') { response.writeHead(404); response.end('{}'); return }
  if (prefix === 'broken') { response.end('{'); return }
  if (prefix === 'html') { response.end('<!DOCTYPE html><title>fallback</title>'); return }
  if (prefix === 'offline') { response.destroy(); return }
  if (prefix) { response.end(JSON.stringify({ mouthes: prefix === 'empty' ? [] : [{ openMouthScale: 3 }] })); return }
  const body = request.url.includes('/other/') ? { positionY: -600 }
    : request.url.includes('body_type') ? { dataList: [] }
    : request.url.includes('idol_motion') ? { entries: {} }
    : request.url.includes('prefab') ? { models: {} } : { by_model_resource_id: {} }
  response.end(JSON.stringify(body))
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const base = `http://127.0.0.1:${server.address().port}`
const originalFetch = globalThis.fetch
globalThis.fetch = (url, options) => originalFetch(new URL(url, base), options)
try {
  for (const prefix of ['own', 'missing', 'broken', 'html', 'empty', 'offline']) {
    const first = requests.length
    const result = await Preloader.preloadScenario(planFor(prefix))
    const task = result.status.tasks.find(task => task.kind === 'model-mouth')
    const plannedRequests = requests.slice(first).filter(url => url.includes('/mouth/'))
    const next = requests.length
    const spine = { _modelName: `${prefix}_001_00` }
    await new LipSyncController({ getSpineEntry: () => null })._loadMouthSetting('040ren', spine)
    const consumerRequests = requests.slice(next)
    assert.deepEqual(plannedRequests, consumerRequests, `${prefix}: executor follows actual consumer fallback boundary`)
    const success = ['own', 'missing'].includes(prefix)
    assert.equal(task.state, success ? 'json-parsed' : 'failed')
    if (prefix === 'html') assert.match(task.error, /Unexpected HTML response/)
    assert.equal(!!spine._mouthData, success)
    assert.equal(result.status.succeeded, success ? 6 : 5)
    assert.equal(result.status.pending, 1, 'logical group is not counted as another parsed config')
    assert.equal(task.uses[0].stepId, 7)
    if (prefix === 'missing') {
      assert.deepEqual(task.attempts.map(attempt => attempt.status), [404, 200])
      assert.match(task.url, /040ren\.json$/)
    }
  }
  const plan = planFor('own')
  for (const asset of plan.assets.filter(asset => !['idol-mouth', 'model-mouth'].includes(asset.kind))) {
    const [url] = storyAssetAdapter(asset).urls
    const data = JSON.parse(await readFile(new URL(`../public${url}`, import.meta.url)))
    validateStoryConfig(asset.kind, data)
  }
  const sameActor = createStoryAssetPlan({ steps: [{ step_id: 1, state: { spines: [
    { id: '040ren', model: '244sub_001_00' }, { id: '040ren', model: '040ren_005_00' },
  ] } }] }, { file: 'fixture.json', sha256: `sha256:${'b'.repeat(64)}` })
  assert.deepEqual(sameActor.assets.find(asset => asset.key === 'idol-mouth:040ren').dependencies,
    ['model-mouth:040ren/244sub_001_00', 'model-mouth:040ren/040ren_005_00'])
  assert.deepEqual(sameActor.assets.find(asset => asset.key === 'model-mouth:040ren/244sub_001_00').candidateIds, ['244sub', '040ren'])
  assert.equal(storyAssetAdapter({ kind: 'model-mouth', modelId: '102sha_001_00' }).state, 'excluded')
  for (const kind of configKinds.filter(kind => kind !== 'idol-mouth')) assert.throws(() => validateStoryConfig(kind, []))

  const controller = new AbortController(), reports = []
  const pending = Preloader.preloadScenario(planFor('slow'), undefined, { signal: controller.signal, onStatus: value => reports.push(value) })
  const deadline = Date.now() + 3000
  while (!requests.some(url => url.endsWith('idol_mouth_stg_slow.json'))) {
    assert.ok(Date.now() < deadline)
    await new Promise(resolve => setImmediate(resolve))
  }
  const mark = requests.length
  controller.abort()
  await assert.rejects(pending, { name: 'AbortError' })
  assert.ok(reports.at(-1).cancelled >= 1)
  assert.equal(reports.at(-1).failed, 0)
  assert.ok(!requests.slice(mark).some(url => url.endsWith('idol_mouth_stg_040ren.json')), 'abort must not launch fallback')
} finally {
  globalThis.fetch = originalFetch
  server.closeAllConnections()
  await new Promise(resolve => server.close(resolve))
}
console.log('Config preload verified: actual mouth consumer parity, HTTP-only fallback, parse/shape failures, model identity, real metadata shapes and cancellation')
