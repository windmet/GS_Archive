/**
 * Translation-only context projection, reference implementation.
 * Input: already source-validated Reading schema v2 rows + published idol dictionary.
 * No fetch, rendering, RAW parsing, name replacement, source mutation or asset loading.
 * Used only by the Studio prepare/check projection; runtime presentation is separate.
 */
export const CONTEXT_SCHEMA = 'GS-STUDIO-CONTEXT-V1'
const HIDDEN = new Set(['?', '？', '???', '？？？'])
const normalizeLookup = value => String(value ?? '').normalize('NFKC').replace(/\s+/gu, '')
const copy = value => value == null ? null : structuredClone(value)

export function buildIdolIndex(dictionary) {
  if (!Array.isArray(dictionary?.idols)) throw new TypeError('Expected published dictionary.idols')
  const byId = new Map()
  for (const idol of dictionary.idols) {
    if (typeof idol.idol_code !== 'string' || !idol.idol_code || !idol.display_name) {
      throw new TypeError('Every idol needs idol_code and display_name')
    }
    if (byId.has(idol.idol_code)) throw new Error(`Duplicate idol code: ${idol.idol_code}`)
    byId.set(idol.idol_code, Object.freeze({
      entity_id: idol.idol_code,
      canonical_ja: idol.display_name,
      lookup_name: normalizeLookup(idol.display_name),
    }))
  }
  return byId
}

function channelFor(row) {
  // presentation is generated by existing CommunicationPresentationContext.
  if (row.presentation === 'call') return { value: 'phone', evidence: 'reader.presentation' }
  if (row.presentation === 'talk') return { value: 'message', evidence: 'reader.presentation' }
  const field = row.text_ref?.source?.field_kind
  if (field === 'phone_message') return { value: 'phone', evidence: 'text_ref.source.field_kind' }
  if (field === 'mobile_message') return { value: 'message', evidence: 'text_ref.source.field_kind' }
  if (row.kind === 'choice' || row.kind === 'choice_detail') return { value: 'choice', evidence: 'reader.kind' }
  if (row.kind === 'dialogue') return { value: 'dialogue', evidence: 'reader.kind' }
  return { value: row.kind || 'unknown', evidence: 'reader.kind' }
}

export function projectStudioContext(row, idolIndex) {
  if (!(idolIndex instanceof Map)) throw new TypeError('Expected idol index Map')
  if (!row?.text_ref?.unit_id || !row.text_ref.source_hash || typeof row.source_text !== 'string') {
    throw new TypeError('Source-bound nonempty text row required')
  }
  const speaker = row.speaker ?? {}
  const display = typeof speaker.sourceName === 'string' ? speaker.sourceName : ''
  const concealed = speaker.kind === 'unknown' || HIDDEN.has(display.trim())
  const context = {
    schema: CONTEXT_SCHEMA,
    unit_id: row.text_ref.unit_id,
    source_hash: row.text_ref.source_hash,
    display_speaker_source: display,
    display_label_policy: concealed ? 'keep-source-concealment' : 'keep-existing-presentation',
    speaker_kind: speaker.kind || 'none',
    actor: { status: 'unresolved', entity_type: null, entity_id: null, canonical_ja: null, evidence: [] },
    channel: channelFor(row),
    // A textual hint, not proof of acting, sound, or script timing.
    expression_hint: /^[（(][\s\S]*[）)]$/u.test(row.source_text.trim())
      ? { value: 'parenthetical', evidence: 'source-punctuation', certainty: 'hint' } : null,
    anchor: copy(row.anchor),
    option: copy(row.option),
    diagnostics: [...(row.diagnostics || [])],
  }
  if (speaker.kind === 'producer') {
    context.actor.status = 'producer'
    context.actor.evidence = ['reader.speaker.kind']
    return context
  }
  if (row.kind !== 'dialogue' || ['none', undefined, null].includes(speaker.kind)) {
    context.actor.status = 'not-attributed'
    return context
  }
  const fromSpeaker = speaker.entityType === 'idol' ? speaker.entityId : null
  const fromPerformance = row.performance?.entityType === 'idol' ? row.performance.entityId : null
  if (context.diagnostics.includes('speaker-performance-conflict') ||
      (fromSpeaker && fromPerformance && fromSpeaker !== fromPerformance) ||
      (speaker.entityType && speaker.entityType !== 'idol' && fromPerformance)) {
    context.actor.status = 'conflict'
    context.actor.candidates = [fromSpeaker, fromPerformance].filter(Boolean)
    return context
  }
  if ((fromSpeaker && !idolIndex.has(fromSpeaker)) || (fromPerformance && !idolIndex.has(fromPerformance))) {
    context.actor.status = 'invalid-id'
    context.actor.candidates = [fromSpeaker, fromPerformance].filter(Boolean)
    return context
  }
  const id = fromSpeaker || fromPerformance
  if (id) {
    context.actor = { status: 'resolved', entity_type: 'idol', entity_id: id,
      canonical_ja: idolIndex.get(id).canonical_ja,
      evidence: [fromSpeaker && 'reader.speaker.entityId', fromPerformance && 'reader.performance.entityId'].filter(Boolean) }
  } else {
    // An NPC description or a visible sprite is NOT a fallback speaker identity.
    context.actor.status = concealed ? 'unresolved' : 'label-only'
  }
  return context
}

/** Explicit option ENTRY links only; never infer exits or reconvergence. */
export function projectChoiceEntryLinks(rows) {
  const targets = new Map()
  for (const row of rows) {
    const index = row.anchor?.step_index
    if (!Number.isInteger(index)) continue
    if (!targets.has(index)) targets.set(index, [])
    targets.get(index).push(row)
  }
  return rows.filter(row => row.kind === 'choice' && row.text_ref).map(row => {
    const option = row.option || {}
    const index = option.target_step_index
    const resolved = option.resolution === 'resolved' && Number.isInteger(index)
    const atTarget = resolved ? (targets.get(index) || []) : []
    return {
      choice_unit_id: row.text_ref.unit_id,
      source_hash: row.text_ref.source_hash,
      choice_id: option.choice_id ?? null,
      option_id: option.option_id ?? null,
      target_step_id: option.target_step_id ?? null,
      target_step_index: index ?? null,
      resolution: option.resolution || 'unresolved',
      target_text_unit_ids: atTarget.map(target => target.text_ref?.unit_id).filter(Boolean),
      graph_completeness: 'entry-only',
      note: resolved && !atTarget.length ? 'Target may be a nontext step; no nearest-text guess.' : null,
    }
  })
}
